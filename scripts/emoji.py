# Slack 이모지 이름표(iamcal emoji-datasource) → internal/core/emoji_table.go
# 실행: cd internal/core && go generate  (버전을 올릴 때만)
import json, sys, urllib.request

VERSION = "15.1.2"
TONES = {"1F3FB": 2, "1F3FC": 3, "1F3FD": 4, "1F3FE": 5, "1F3FF": 6}

def chars(unified):
    return "".join(chr(int(h, 16)) for h in unified.split("-"))

data = json.load(urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/emoji-datasource@{VERSION}/emoji.json"))
table = {}
for e in data:
    for name in e["short_names"]:
        if name.startswith("skin-tone-"):  # 견본 단독 — :custom::skin-tone-3:에서 따로 맞지 않게
            continue
        table[name] = chars(e["unified"])
        for key, v in (e.get("skin_variations") or {}).items():
            if key in TONES:  # 한 가지 톤만(두 사람 이모지의 섞인 톤은 뺀다)
                table[f"{name}::skin-tone-{TONES[key]}"] = chars(v["unified"])

out = sys.argv[1] if len(sys.argv) > 1 else "emoji_table.go"
with open(out, "w") as f:
    f.write(f"// Code generated by scripts/emoji.py from emoji-datasource@{VERSION}; DO NOT EDIT.\n\npackage core\n\nvar emojiTable = map[string]string{{\n")
    for k in sorted(table):
        f.write(f"\t{json.dumps(k)}: {json.dumps(table[k], ensure_ascii=False)},\n")
    f.write("}\n")
print(len(table), "names")
